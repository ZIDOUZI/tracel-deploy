//! xtask-like binary that adds a deploy command on top of
//! `tracel_xtask_macros::base_commands`.
//!
//! The attributes show the two customization points of
//! [`tracel_deploy::deploy_commands`]:
//!
//! - `args = MyDeployArgs`: a project specific args struct that flattens
//!   [`tracel_deploy::DeployCmdArgs`] and adds local flags.
//! - `handler_name = run_deploy`: a custom name for the generated dispatcher
//!   (the default is `handle_deploy_command`).
//!
//! `deploy_commands` is written above `base_commands` on purpose: the reverse
//! order drops the deploy command. See the `tracel-deploy-macros` README.
use tracel_deploy::prelude::*;
use tracel_xtask::prelude::*;

/// Project specific deploy arguments: the shared `DeployCmdArgs` plus whatever
/// this project needs.
#[derive(clap::Args, Clone, Debug)]
pub struct MyDeployArgs {
    #[command(flatten)]
    pub deploy: tracel_deploy::DeployCmdArgs,
    /// Extra seconds to wait for the deployed binary to answer.
    #[arg(long, value_name = "SECS")]
    pub verify_timeout: Option<u64>,
}

#[tracel_deploy::deploy_commands(
    Deploy,
    args = MyDeployArgs,
    handler = handle_deploy,
    handler_name = run_deploy
)]
#[macros::base_commands(Build, Check, Test)]
pub enum Command {
    Custom(CustomArgs),
}

#[derive(clap::Args, Clone, Debug)]
pub struct CustomArgs {
    #[arg(long)]
    pub name: Option<String>,
}

fn handle_deploy(
    args: MyDeployArgs,
    _environment: Environment,
    _context: Context,
) -> anyhow::Result<()> {
    let _ = (args.deploy.release, args.verify_timeout);
    Ok(())
}

fn main() -> anyhow::Result<()> {
    let args = init_xtask::<Command>(parse_args::<Command>()?)?;
    match args.command {
        Command::Custom(_) => Ok(()),
        // Generated by `handler_name = run_deploy`; without `handler_name` this
        // dispatcher would be called `handle_deploy_command`.
        Command::Deploy(command) => run_deploy(command, args.environment, args.context),
        _ => dispatch_base_commands(args),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::Parser;

    #[derive(Parser)]
    struct Cli {
        #[command(subcommand)]
        command: Command,
    }

    /// Attribute defaults: no `args`, no `handler_name`, so the variant carries
    /// `DeployCmdArgs` and the dispatcher is named `handle_deploy_command`.
    mod defaults {
        use tracel_xtask::prelude::*;

        #[tracel_deploy::deploy_commands(Deploy, handler = handle_deploy)]
        pub enum Command {
            Local,
        }

        fn handle_deploy(
            _args: tracel_deploy::DeployCmdArgs,
            _environment: Environment,
            _context: Context,
        ) -> anyhow::Result<()> {
            Ok(())
        }

        pub fn dispatch(
            command: Command,
            environment: Environment,
            context: Context,
        ) -> anyhow::Result<()> {
            match command {
                Command::Deploy(args) => {
                    // The default dispatcher name, generated by `handler`.
                    handle_deploy_command(args, environment, context)
                }
                Command::Local => Ok(()),
            }
        }
    }

    #[test]
    fn deploy_variant_uses_custom_args_and_parses() {
        let cli = Cli::try_parse_from([
            "xtask",
            "deploy",
            "--release",
            "--dry-run",
            "--verify-timeout",
            "30",
        ])
        .expect("deploy subcommand parses");
        match cli.command {
            Command::Deploy(args) => {
                assert!(args.deploy.release);
                assert!(args.deploy.dry_run);
                assert_eq!(args.verify_timeout, Some(30));
            }
            _ => panic!("expected generated deploy variant"),
        }
    }

    #[test]
    fn default_handler_name_is_still_generated() {
        let _dispatch: fn(defaults::Command, Environment, Context) -> anyhow::Result<()> =
            defaults::dispatch;
    }
}
